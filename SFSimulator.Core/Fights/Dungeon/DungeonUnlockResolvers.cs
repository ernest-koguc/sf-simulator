            130 => c => c.CharacterLevel >= 640,
            131 => c => c.CharacterLevel >= 660,
            132 => c => c.CharacterLevel >= 680,
            133 => c => c.CharacterLevel >= 700,

            201 => c => c.CharacterLevel >= 250,
            202 => c => c.CharacterLevel >= 255,
            203 => c => c.CharacterLevel >= 260,
            204 => c => c.CharacterLevel >= 265,

            -1 => c => c.Dungeons.Where(d => d.Position >= 1 && d.Position <= 9).All(d => d.IsDefeated),
            -2 => c => c.Dungeons.First(d => d.Type == DungeonTypeEnum.Tower).IsUnlocked,
            -3 => c => c.Dungeons.First(d => d.Type == DungeonTypeEnum.Tower).IsUnlocked && c.CharacterLevel >= 222,
            -4 => c => c.Dungeons.First(d => d.Position == 28).IsDefeated && c.CharacterLevel >= 500,
            _ => c => true,
        };
    }
}