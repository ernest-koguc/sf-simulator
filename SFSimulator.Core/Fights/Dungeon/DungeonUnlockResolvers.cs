namespace SFSimulator.Core;

public static class DungeonUnlockResolvers
{
    public static Func<DungeonUnlockContext, bool> Get(int index)
    {
        return index switch
        {
            1 => c => c.CharacterLevel >= 10,
            2 => c => c.CharacterLevel >= 20,
            3 => c => c.CharacterLevel >= 30,
            4 => c => c.CharacterLevel >= 40,
            5 => c => c.CharacterLevel >= 50,
            6 => c => c.CharacterLevel >= 70,
            7 => c => c.CharacterLevel >= 80,
            8 => c => c.CharacterLevel >= 95,
            9 => c => c.CharacterLevel >= 110,
