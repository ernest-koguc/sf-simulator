            11 => c => c.Dungeons.First(d => d.Position == 10).IsDefeated,
            12 => c => c.Dungeons.First(d => d.Position == 11).IsDefeated,
            13 => c => c.CharacterLevel >= 210,
            14 => c => c.CharacterLevel >= 240,
            15 => c => c.Dungeons.First(d => d.Position == 12).IsUnlocked,
            16 => c => c.CharacterLevel >= 280,
            17 => c => c.CharacterLevel >= 200,
            18 => c => c.Dungeons.First(d => d.Position == 11).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            19 => c => c.Dungeons.First(d => d.Position == 11).IsUnlocked,
            20 => c => c.CharacterLevel >= 340,
            21 => c => c.CharacterLevel >= 270,
            22 => c => c.Dungeons.First(d => d.Position == 19).IsDefeated,
            23 => c => c.Dungeons.First(d => d.Position == 17).IsDefeated,
            24 => c => c.CharacterLevel >= 180,
            25 => c => c.Dungeons.First(d => d.Position == 18).IsDefeated,
            26 => c => c.Dungeons.First(d => d.Position == 15).IsDefeated,
            27 => c => c.CharacterLevel >= 200,
            28 => c => c.CharacterLevel >= 480,
            29 => c => c.CharacterLevel >= 500,
            30 => c => c.CharacterLevel >= 520,
            31 => c => c.CharacterLevel >= 540,
            32 => c => c.CharacterLevel >= 560,
            33 => c => c.CharacterLevel >= 580,

            101 => c => c.Dungeons.First(d => d.Type == DungeonTypeEnum.Tower).IsUnlocked && c.CharacterLevel >= 140,
            102 => c => c.Dungeons.First(d => d.Position == 101).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            103 => c => c.Dungeons.First(d => d.Position == 102).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            104 => c => c.Dungeons.First(d => d.Position == 103).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            105 => c => c.Dungeons.First(d => d.Position == 104).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            106 => c => c.Dungeons.First(d => d.Position == 106).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            107 => c => c.Dungeons.First(d => d.Position == 106).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            108 => c => c.Dungeons.First(d => d.Position == 107).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            109 => c => c.Dungeons.First(d => d.Position == 108).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            110 => c => c.Dungeons.First(d => d.Position == 109).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            111 => c => c.Dungeons.First(d => d.Position == 110).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            112 => c => c.Dungeons.First(d => d.Position == 111).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            113 => c => c.CharacterLevel >= 320,
            114 => c => c.CharacterLevel >= 350,
            115 => c => c.Dungeons.First(d => d.Position == 112).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            116 => c => c.CharacterLevel >= 370,
            117 => c => c.CharacterLevel >= 350,
            118 => c => c.Dungeons.First(d => d.Position == 112).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            119 => c => c.Dungeons.First(d => d.Position == 115).DungeonEnemies.First(e => e.Position == 5).IsDefeated,
            120 => c => c.CharacterLevel >= 500,
            121 => c => c.CharacterLevel >= 350,
            122 => c => c.Dungeons.First(d => d.Position == 119).IsDefeated,
            123 => c => c.Dungeons.First(d => d.Position == 117).IsDefeated,
            124 => c => c.CharacterLevel >= 280,
            125 => c => c.Dungeons.First(d => d.Position == 118).IsDefeated,
